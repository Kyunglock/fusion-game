/** word → category 역인덱스. 저장된 그림의 제시어가 아직 사전에 있는지 확인할 때도 쓴다. */
export const WORD_CATEGORY = new Map();
for (const [key, words] of Object.entries(WORDS_BY_CATEGORY)) {
  for (const w of words) WORD_CATEGORY.set(w, key);
}

/** 전체 제시어 (중복 제거) */
export const ALL_WORDS = [...WORD_CATEGORY.keys()];

/** 사전에 있는 제시어인지 */
export function isKnownWord(word) {
  return WORD_CATEGORY.has(word);
}

/** 제시어의 카테고리 정보 (없으면 null) */
export function categoryOf(word) {
  const key = WORD_CATEGORY.get(word);
  return key ? { key, ...CATEGORIES[key] } : null;
}

/**
 * 그릴 제시어를 하나 고른다.
 *
 * 완전 무작위로 뽑으면 인기 단어에만 그림이 몰려 맞히기 쪽이 금방 지루해진다.
 * 그래서 후보를 여러 개 뽑아 그중 **그림이 가장 적게 쌓인 것**을 준다.
 *
 * @param {Map<string, number>} counts   word → 지금까지 그려진 그림 수
 * @param {Set<string>} [exclude]        피하고 싶은 제시어 (방금 새로고침한 것 등)
 */
export function pickWord(counts = new Map(), exclude = new Set()) {
  const pool = ALL_WORDS.length > exclude.size
    ? ALL_WORDS.filter(w => !exclude.has(w))
    : ALL_WORDS;

  let best = null;
  let bestCount = Infinity;
  // 후보 8개를 뽑아 그중 가장 덜 그려진 것 — 완전 결정적이지 않으면서도 쏠림을 막는다.
  for (let i = 0; i < 8; i++) {
    const cand = pool[Math.floor(Math.random() * pool.length)];
    const c    = counts.get(cand) ?? 0;
    if (c < bestCount) { best = cand; bestCount = c; }
    if (bestCount === 0) break;
  }
  return best;
}
